const imageSources = new Map();

export function createCategoryMarkerImage(maps, category, isFavorite = false) {
  const name = Object.hasOwn(CATEGORY_SVG, category)
    ? category
    : category
      ? '기타'
      : '';
  const key = name + ':' + Boolean(isFavorite);

  if (!imageSources.has(key)) {
    const color = isFavorite ? '#ef5350' : '#268df5';
    const svg =
      '<svg xmlns="http://www.w3.org/2000/svg" width="44" height="54" viewBox="0 0 44 54">' +
      '<path d="M22 2C11.5 2 3 10.5 3 21c0 13.4 19 31 19 31s19-17.6 19-31C41 10.5 32.5 2 22 2Z" fill="' +
      color +
      '" stroke="#fff" stroke-width="2" stroke-linejoin="round"/>' +
      CATEGORY_SVG[name] +
      '</svg>';
    imageSources.set(
      key,
      'data:image/svg+xml;charset=UTF-8,' + encodeURIComponent(svg),
    );
  }

  return new maps.MarkerImage(imageSources.get(key), new maps.Size(44, 54), {
    offset: new maps.Point(22, 52),
  });
}
